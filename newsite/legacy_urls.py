"""Replacements for the pre-2026-07 flat site, at URLs the host still serves.

The old English-only site was replaced on 2026-07-19 (commit a3e72dc0) and its
29 files were deleted from git. They are still live. Render publishes additively
and never prunes, so every one of them has survived every deploy since, and on
2026-10-26 all 29 still answered 200 carrying:

  * the placeholder phone number +1 888 555 0142, four to seven times a page,
    the exact string CLAUDE.md lists as a pre-deploy blocker
  * "[Your Company] LLC"
  * the retired "we are not a travel agency / we do not sell, book, ticket or
    take payment" paragraph, which is now the opposite of true

None of that can be fixed by editing a generator, because no generator writes
these URLs any more. Deleting the local copies does not help either: the files
served are the ones committed in 2026, not the ones on this disk. A server-side
redirect is not available, the Blueprint route is not active and the domain root
still answers 200 rather than redirecting.

So the build writes a replacement AT each URL. Same reasoning and same shape as
retired.py, which solves this for the four retired ship pages. Each stub is
noindex, canonicals to the live equivalent, redirects, and says in a sentence
what happened, because someone arriving on a three-year-old bookmark deserves a
readable answer and not a silent bounce.

Every target below was confirmed to exist in the current build before this list
was written. The old site was English-only, so these are /en/ targets.
"""

